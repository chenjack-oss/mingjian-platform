# 子智能体（P6）
#
# 目录约定：
#   contracts.py   子智能体的**返回契约**（所有子智能体必须遵守，应用层强制校验）
#   kb_analyst.py  知识库子智能体（第一个接入的）
#   registry.py    按档位装配子智能体清单
#
# 设计红线（写在这里是因为它们容易被后来的改动破坏）：
#   1. 子智能体的最终回复必须是 contracts.SubAgentResult 的 JSON 信封，不是自由文本。
#      原因：deepagents 把子智能体的**最后一条 AIMessage 文本**回传给主智能体
#      （middleware/subagents.py:743），主智能体没有任何结构化手段判断这段话
#      是查到的还是编的 —— 这正是我们要防的。
#   2. 子智能体只拿自己那几个工具（graph.py:762 支持 per-subagent 工具覆盖），
#      主智能体不再握有这些工具。工具边界 = 权限边界，同时也是准确率边界
#      （P5 实测：工具 3 个 → 16 个，选择准确率 100% → 90%）。
